"""Compiles the native passes' shaders (runtime/gs/gpu/native/shaders/*.comp, *.vert, *.frag) into the headers the
runtime embeds (<name>_spv.h next to a compute shader, <name>_vert_spv.h and <name>_frag_spv.h for the others), with
the Vulkan SDK's glslc. --check only reports headers that differ.

python tools/graphics/gpu/build_native_shaders.py [--check]
"""
import argparse
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[3]
SHADERS = ROOT / 'runtime' / 'gs' / 'gpu' / 'native' / 'shaders'
FLAGS = ['--target-env=vulkan1.1', '-O']
STAGES = {'.comp': ('compute', ''), '.vert': ('vertex', '_vert'), '.frag': ('fragment', '_frag')}


def glslc():
    found = shutil.which('glslc')
    if found:
        return found
    sdk = os.environ.get('VULKAN_SDK')
    if sdk and (pathlib.Path(sdk) / 'Bin' / 'glslc.exe').exists():
        return str(pathlib.Path(sdk) / 'Bin' / 'glslc.exe')
    sys.exit('glslc not found: install the Vulkan SDK')


def header(source, words):
    stage, suffix = STAGES[source.suffix]
    name = source.stem + suffix
    lines = [f'// Generated by tools/graphics/gpu/build_native_shaders.py from shaders/{source.name} (glslc {" ".join(FLAGS)} -fshader-stage={stage}).',
             '#pragma once', '#include <cstdint>', '',
             f'inline constexpr std::uint32_t {name}_spv[] = {{']
    for at in range(0, len(words), 8):
        lines.append('    ' + ','.join(f'0x{w:08x}u' for w in words[at:at + 8]) + ',')
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    compiler = glslc()
    stale = []
    for source in sorted(p for p in SHADERS.iterdir() if p.suffix in STAGES):
        stage, suffix = STAGES[source.suffix]
        with tempfile.TemporaryDirectory() as folder:
            out = pathlib.Path(folder) / 'shader.spv'
            subprocess.run([compiler, *FLAGS, f'-fshader-stage={stage}', str(source), '-o', str(out)], check=True)
            data = out.read_bytes()
        words = [int.from_bytes(data[at:at + 4], 'little') for at in range(0, len(data), 4)]
        target = source.with_name(source.stem + suffix + '_spv.h')
        text = header(source, words)
        if target.exists() and target.read_text(encoding='utf-8') == text:
            continue
        stale.append(target)
        if not args.check:
            target.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', target.relative_to(ROOT))
    if args.check and stale:
        sys.exit('out of date: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))


if __name__ == '__main__':
    main()
